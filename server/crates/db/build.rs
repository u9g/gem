use std::{env, fs, path::PathBuf};

// Writes src/migrations.rs, MIGRATIONS: each file in migrations/ by its name without `.sql`, and
// its SQL, oldest first. Checked in rather than included from OUT_DIR, because lust does not see
// items an `include!` brings in; written only when it changed.
fn main() {
    println!("cargo:rerun-if-changed=migrations");
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let mut names: Vec<String> = fs::read_dir(root.join("migrations"))
        .unwrap()
        .map(|entry| entry.unwrap().file_name().to_string_lossy().into_owned())
        .filter(|name| name.ends_with(".sql"))
        .collect();
    names.sort();
    let entries: String = (names.iter())
        .map(|name| {
            let stem = name.trim_end_matches(".sql");
            format!("    ({stem:?}, include_str!(\"../migrations/{name}\")),\n")
        })
        .collect();
    let code = format!(
        "// Generated by build.rs from migrations/. Do not edit.\n\npub const MIGRATIONS: &[(&str, &str)] = &[\n{entries}];\n"
    );
    let out = root.join("src/migrations.rs");
    if fs::read_to_string(&out).ok().as_deref() != Some(code.as_str()) {
        fs::write(out, code).unwrap();
    }
}
